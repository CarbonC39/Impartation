import { readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const characters = join(root, 'assets/characters');
const output = join(root, 'packages/shared/src/appearanceAssets.generated.ts');
const categories = ['body', 'face', 'hair', 'top', 'bottom', 'shoes', 'accessories'];
const assets = {};
const paths = {};

for (const category of categories) {
  const folder = join(characters, category);
  let files = [];
  try { files = await readdir(folder); } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  // Numeric-aware order, so hair10 follows hair9 in the wardrobe.
  const pngFiles = files.filter(file => file.toLowerCase().endsWith('.png'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  const ids = pngFiles.map(file => file.slice(0, -4));
  for (const [index, id] of ids.entries()) {
    if (!/^[\p{L}\p{N}_-]+$/u.test(id)) throw new Error(`Invalid character asset filename: ${category}/${id}.png`);
    if (Object.hasOwn(paths, id)) throw new Error(`Duplicate character asset ID: ${id}`);
    paths[id] = `/${relative(join(root, 'assets'), join(folder, pngFiles[index])).split(sep).join('/')}`;
  }
  assets[category] = ids;
}

for (const category of ['top', 'bottom', 'shoes', 'accessories']) assets[category].unshift('none');
for (const required of ['body', 'face']) {
  if (!assets[required].length) throw new Error(`Add at least one PNG to assets/characters/${required}/`);
}

const source = `// Generated by scripts/generate-appearance-assets.mjs; edit files in assets/characters/<category>/ instead.\n` +
  `export const APPEARANCE_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n` +
  `export const APPEARANCE_ASSET_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`;
await writeFile(output, source);
